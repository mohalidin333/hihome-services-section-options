/* =====================================================
   ServiceIconResolver
   Maps a ServiceItem["icon"] string to the correct
   SVG component. Use anywhere a service icon is needed.
   ===================================================== */
export function ServiceIconResolver({
  icon,
  size = 24,
}: {
  icon: "home" | "tag" | "building" | "chart";
  size?: number;
}) {
  switch (icon) {
    case "home":
      return <HomeIcon size={size} />;
    case "tag":
      return <TagIcon size={size} />;
    case "building":
      return <BuildingIcon size={size} />;
    case "chart":
      return <ChartIcon size={size} />;
  }
}
